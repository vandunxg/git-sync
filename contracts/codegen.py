#!/usr/bin/env python3
"""Generate Rust and TypeScript contract bindings from dtos.schema.json + ipc.v1.json.

Outputs (committed, never hand-edited):
  crates/domain/src/contract/generated.rs
  apps/desktop/src/lib/native/generated/contract.ts
  contracts/fixtures/cases.json   (shared positive/negative validation cases)

`--check` regenerates in memory and exits 1 when any output is stale, so CI detects
FE/native drift. Supports only the schema subset already accepted by
scripts/contract_checks.py; anything else is a hard error, not a silent fallback.
Expected case verdicts come from scripts/contract_checks.py (the blueprint oracle).
"""
from __future__ import annotations

import argparse
import copy
import json
import re
import subprocess
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
import contract_checks  # noqa: E402  (blueprint validator used as the oracle)

SCHEMA_PATH = ROOT / "contracts/dtos.schema.json"
IPC_PATH = ROOT / "contracts/ipc.v1.json"
RUST_OUT = ROOT / "crates/domain/src/contract/generated.rs"
TS_OUT = ROOT / "apps/desktop/src/lib/native/generated/contract.ts"
CASES_OUT = ROOT / "contracts/fixtures/cases.json"
TS_CASES_OUT = ROOT / "apps/desktop/src/lib/native/generated/cases.ts"

HEADER = "Generated by contracts/codegen.py from contracts/dtos.schema.json and contracts/ipc.v1.json. Do not edit."

# Deterministic sample strings for the patterns used by the schema. Unknown patterns fail.
PATTERN_SAMPLES = {
    "^[A-Za-z0-9][A-Za-z0-9._:-]{0,127}$": "id-0001",
    "^refs/(heads|tags)/.+$": "refs/heads/main",
    "^[0-9]+$": "123456",
    "^([0-9a-f]{40}|[0-9a-f]{64})$": "0" * 40,
}
SAMPLE_DATE_TIME = "2026-01-01T00:00:00Z"


def pascal(name: str) -> str:
    parts = re.split(r"[^A-Za-z0-9]+", name)
    out = "".join(p[:1].upper() + p[1:] for p in parts if p)
    return out if out[:1].isalpha() else "V" + out


def snake(name: str) -> str:
    s = re.sub(r"(?<=[a-z0-9])([A-Z])", r"_\1", name).lower()
    return {"type": "r#type", "ref": "r#ref", "self": "self_", "move": "r#move"}.get(s, s)


def ref_name(node: dict[str, Any]) -> str | None:
    ref = node.get("$ref")
    return ref[len("#/$defs/"):] if ref else None


def split_nullable(node: dict[str, Any]) -> tuple[dict[str, Any], bool]:
    """Return (non-null schema, nullable) for `type: [T, null]` and `anyOf: [X, null]`."""
    if "anyOf" in node:
        branches = node["anyOf"]
        non_null = [b for b in branches if b.get("type") != "null"]
        if len(branches) != 2 or len(non_null) != 1:
            raise SystemExit(f"unsupported anyOf shape: {node}")
        return non_null[0], True
    t = node.get("type")
    if isinstance(t, list):
        rest = [x for x in t if x != "null"]
        if len(rest) != 1 or len(t) != 2:
            raise SystemExit(f"unsupported type list: {t}")
        inner = dict(node)
        inner["type"] = rest[0]
        if "enum" in inner:  # nullable enum lists null as a member
            inner["enum"] = [v for v in inner["enum"] if v is not None]
        return inner, True
    return node, False


def ecma_pattern(pattern: str) -> str:
    """Translate a schema pattern to Python `re` with ECMA-262 (no flags) semantics:
    `$` matches only at end of input and `.` excludes all ECMA line terminators."""
    out, in_class, i = [], False, 0
    while i < len(pattern):
        ch = pattern[i]
        if ch == "\\":
            out.append(pattern[i:i + 2])
            i += 2
            continue
        if ch == "[":
            in_class = True
        elif ch == "]":
            in_class = False
        elif not in_class and ch == ".":
            ch = "[^\\n\\r\\u2028\\u2029]"
        elif not in_class and ch == "$":
            ch = "\\Z"
        out.append(ch)
        i += 1
    return "".join(out)


RFC3339 = re.compile(r"^\d{4}-\d{2}-\d{2}[Tt]\d{2}:\d{2}:\d{2}(\.\d+)?([Zz]|[+-]\d{2}:\d{2})\Z")


def strict_violation(value: Any, node: dict[str, Any], root: dict[str, Any], depth: int = 0) -> bool:
    """True when the blueprint oracle (scripts/contract_checks.py, Python `re` and
    `datetime.fromisoformat`) accepts a value the contract semantics reject:
    - patterns: JSON Schema uses ECMA-262 regex semantics (see ecma_pattern);
    - date-time: RFC 3339 profile (`T`, seconds, `Z` or `+HH:MM`), stricter than fromisoformat.
    Corrected here instead of editing the blueprint oracle; recorded in the P01-T02 report."""
    if depth > 80:
        return False
    r = ref_name(node)
    if r:
        return strict_violation(value, root["$defs"][r], root, depth + 1)
    if "anyOf" in node:
        inner, _ = split_nullable(node)
        return strict_violation(value, inner, root, depth + 1)
    if isinstance(value, str):
        if "pattern" in node and re.search(ecma_pattern(node["pattern"]), value) is None:
            return True
        return node.get("format") == "date-time" and RFC3339.match(value) is None
    if isinstance(value, dict):
        props = node.get("properties", {})
        return any(strict_violation(v, props[k], root, depth + 1) for k, v in value.items() if k in props)
    if isinstance(value, list) and "items" in node:
        return any(strict_violation(v, node["items"], root, depth + 1) for v in value)
    return False


def rustfmt(text: str) -> str:
    """Format generated Rust with the workspace toolchain so `cargo fmt --check` holds."""
    result = subprocess.run(["rustfmt", "--edition", "2024", "--emit", "stdout"], input=text,
                            capture_output=True, text=True, timeout=60, check=False)
    if result.returncode:
        raise SystemExit("rustfmt failed on generated Rust: " + result.stderr[:2000])
    return result.stdout


class Model:
    def __init__(self, schema: dict[str, Any], ipc: dict[str, Any]) -> None:
        self.schema = schema
        self.defs: dict[str, Any] = schema["$defs"]
        self.ipc = ipc
        self.inline_enums: dict[str, list[str]] = {}

    # ---------- Rust ----------
    def rust_type(self, owner: str, field: str, node: dict[str, Any]) -> str:
        inner, nullable = split_nullable(node)
        base = self.rust_base(owner, field, inner)
        return f"Option<{base}>" if nullable else base

    def rust_base(self, owner: str, field: str, node: dict[str, Any]) -> str:
        r = ref_name(node)
        if r:
            return r
        if "const" in node:
            c = node["const"]
            return {bool: "bool", int: "i64"}[type(c)]
        t = node.get("type")
        if t == "string":
            if "enum" in node:
                name = owner + pascal(field)
                self.inline_enums[name] = node["enum"]
                return name
            return "SecretString" if node.get("writeOnly") else "String"
        if t == "integer":
            return "i64"
        if t == "number":
            return "f64"
        if t == "boolean":
            return "bool"
        if t == "array":
            return f"Vec<{self.rust_base(owner, field + 'Item', node['items'])}>"
        raise SystemExit(f"unsupported node in {owner}.{field}: {node}")

    def has_secret(self, name: str, seen: set[str] | None = None) -> bool:
        seen = seen or set()
        if name in seen:
            return False
        seen.add(name)
        d = self.defs[name]
        for p in d.get("properties", {}).values():
            inner, _ = split_nullable(p)
            if inner.get("writeOnly"):
                return True
            r = ref_name(inner) or ref_name(inner.get("items", {}))
            if r and self.has_secret(r, seen):
                return True
        return False

    def render_rust(self) -> str:
        out: list[str] = [f"// {HEADER}", "//", "// Secret-bearing DTOs derive only Deserialize (no Debug/Serialize, R-RUST).", ""]
        out += ["use serde::{Deserialize, Serialize};", "", "use super::secret::SecretString;", ""]
        body: list[str] = []
        for name, d in self.defs.items():
            t = d.get("type")
            if t == "object":
                secret = self.has_secret(name)
                derives = "Deserialize" if secret else "Debug, Clone, PartialEq, Serialize, Deserialize"
                body.append(f"#[derive({derives})]")
                body.append("#[serde(deny_unknown_fields)]")
                fields = d.get("properties", {})
                if not fields:
                    body.append(f"pub struct {name} {{}}")
                    body.append("")
                    continue
                body.append(f"pub struct {name} {{")
                for prop, node in fields.items():
                    body.append(f'    #[serde(rename = "{prop}")]')
                    body.append(f"    pub {snake(prop)}: {self.rust_type(name, prop, node)},")
                body.append("}")
                body.append("")
            elif t == "string" and "enum" in d:
                self.inline_enums[name] = d["enum"]
            elif t == "string":
                body.append(f"pub type {name} = String;")
                body.append("")
            elif t == "integer":
                body.append(f"pub type {name} = i64;")
                body.append("")
            else:
                raise SystemExit(f"unsupported top-level def {name}")
        enums: list[str] = []
        for name, values in sorted(self.inline_enums.items()):
            enums.append("#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Serialize, Deserialize)]")
            enums.append(f"pub enum {name} {{")
            for v in values:
                enums.append(f'    #[serde(rename = "{v}")]')
                enums.append(f"    {pascal(v.lower()) if v.isupper() else pascal(v)},")
            enums.append("}")
            enums.append("")
        cmds = self.ipc["commands"]
        table = ["/// One app-owned IPC command from contracts/ipc.v1.json.",
                 "#[derive(Debug, Clone, Copy, PartialEq, Eq)]",
                 "pub struct CommandSpec {",
                 "    pub name: &'static str,",
                 "    pub request_type: &'static str,",
                 "    pub response_type: &'static str,",
                 "    pub effect: &'static str,",
                 "    pub sensitive: bool,",
                 "}", "",
                 f"pub const COMMANDS: [CommandSpec; {len(cmds)}] = ["]
        for c in cmds:
            table.append(f'    CommandSpec {{ name: "{c["name"]}", request_type: "{c["requestType"]}", '
                         f'response_type: "{c["responseType"]}", effect: "{c["effect"]}", sensitive: {str(c["sensitive"]).lower()} }},')
        table += ["];", ""]
        forb = self.ipc["forbidden"]
        table += [f"pub const FORBIDDEN_COMMANDS: [&str; {len(forb)}] = [" + ", ".join(f'"{f}"' for f in forb) + "];", ""]
        table += [f"pub const SCHEMA_VERSION: i64 = {self.ipc['schemaVersion']};", ""]
        rt = ["/// Deserializes `value` as `definition` and serializes it back (contract parity tests).",
              "/// Returns `Ok(None)` for aliases and for secret-bearing DTOs, which cannot serialize.",
              "pub fn typed_roundtrip(",
              "    definition: &str,",
              "    value: &serde_json::Value,",
              ") -> Result<Option<serde_json::Value>, serde_json::Error> {",
              "    match definition {"]
        for name, d in self.defs.items():
            if d.get("type") == "object":
                if self.has_secret(name):
                    rt.append(f'        "{name}" => serde_json::from_value::<{name}>(value.clone()).map(|_| None),')
                else:
                    rt.append(f'        "{name}" => serde_json::to_value(serde_json::from_value::<{name}>(value.clone())?).map(Some),')
            elif "enum" in d:
                rt.append(f'        "{name}" => serde_json::to_value(serde_json::from_value::<{name}>(value.clone())?).map(Some),')
        rt += ["        _ => Ok(None),", "    }", "}", ""]
        text = "\n".join(out + body + enums + table + rt)
        return rustfmt(text.rstrip() + "\n")

    # ---------- TypeScript ----------
    def ts_type(self, node: dict[str, Any]) -> str:
        inner, nullable = split_nullable(node)
        base = self.ts_base(inner)
        return f"{base} | null" if nullable else base

    def ts_base(self, node: dict[str, Any]) -> str:
        r = ref_name(node)
        if r:
            return r
        if "const" in node:
            return json.dumps(node["const"])
        t = node.get("type")
        if t == "string":
            return " | ".join(json.dumps(v) for v in node["enum"]) if "enum" in node else "string"
        if t in ("integer", "number"):
            return "number"
        if t == "boolean":
            return "boolean"
        if t == "array":
            item = self.ts_base(node["items"])
            return f"Array<{item}>" if "|" in item else f"{item}[]"
        raise SystemExit(f"unsupported TS node {node}")

    def render_ts(self) -> str:
        lines = [f"// {HEADER}", ""]
        for name, d in self.defs.items():
            t = d.get("type")
            if t == "object":
                props = d.get("properties", {})
                if not props:
                    lines.append(f"export type {name} = Record<string, never>")
                else:
                    lines.append(f"export interface {name} {{")
                    for p, node in props.items():
                        lines.append(f"  {p}: {self.ts_type(node)}")
                    lines.append("}")
            else:
                lines.append(f"export type {name} = {self.ts_base(d)}")
            lines.append("")
        lines.append("export interface CommandMap {")
        for c in self.ipc["commands"]:
            lines.append(f'  {c["name"]}: {{ request: {c["requestType"]}; response: {c["responseType"]} }}')
        lines += ["}", "", "export type CommandName = keyof CommandMap", ""]
        lines.append("export const COMMANDS = " + json.dumps(
            {c["name"]: {"requestType": c["requestType"], "responseType": c["responseType"], "sensitive": c["sensitive"]}
             for c in self.ipc["commands"]}, indent=2) + " as const")
        lines.append("")
        lines.append(f"export const SCHEMA_VERSION = {self.ipc['schemaVersion']} as const")
        lines.append("")
        lines.append("export const DTO_SCHEMA = " + json.dumps(self.schema, indent=2, ensure_ascii=True) + " as const")
        lines.append("")
        return "\n".join(lines)

    # ---------- shared cases ----------
    def sample(self, node: dict[str, Any], depth: int = 0) -> Any:
        if depth > 40:
            raise SystemExit("sample recursion")
        r = ref_name(node)
        if r:
            return self.sample(self.defs[r], depth + 1)
        if "anyOf" in node:
            return self.sample(split_nullable(node)[0], depth + 1)
        if "const" in node:
            return node["const"]
        t = node.get("type")
        if isinstance(t, list):
            return self.sample(split_nullable(node)[0], depth + 1)
        if t == "object":
            return {p: self.sample(s, depth + 1) for p, s in node.get("properties", {}).items()}
        if t == "string":
            if "enum" in node:
                return node["enum"][0]
            if "pattern" in node:
                if node["pattern"] not in PATTERN_SAMPLES:
                    raise SystemExit(f"no sample for pattern {node['pattern']}")
                return PATTERN_SAMPLES[node["pattern"]]
            if node.get("format") == "date-time":
                return SAMPLE_DATE_TIME
            return "x" * max(1, node.get("minLength", 1))
        if t == "integer":
            return max(node.get("minimum", 1), min(1, node.get("maximum", 1)))
        if t == "number":
            return float(node.get("minimum", 0)) + 0.5 if node.get("maximum", 100) >= node.get("minimum", 0) + 0.5 else float(node.get("minimum", 0))
        if t == "boolean":
            return False
        if t == "array":
            n = max(1, node.get("minItems", 0))
            return [self.sample(node["items"], depth + 1) for _ in range(n)]
        raise SystemExit(f"cannot sample {node}")

    def cases(self) -> list[dict[str, Any]]:
        cases: list[dict[str, Any]] = []

        def add(def_name: str, label: str, value: Any) -> None:
            errors = contract_checks.validate(value, self.defs[def_name], self.schema)
            valid = not errors and not strict_violation(value, self.defs[def_name], self.schema)
            cases.append({"def": def_name, "label": label, "value": value, "valid": valid})

        for name, d in self.defs.items():
            base = self.sample(d)
            add(name, "sample", base)
            if d.get("type") != "object":
                add(name, "wrong-type", [] if not isinstance(base, list) else {})
                continue
            add(name, "extra-property", {**base, "unexpectedField": 1})
            for prop, node in d.get("properties", {}).items():
                missing = copy.deepcopy(base)
                del missing[prop]
                add(name, f"missing:{prop}", missing)
                inner, nullable = split_nullable(node)
                nulled = copy.deepcopy(base)
                nulled[prop] = None
                add(name, f"null:{prop}", nulled)
                wrong = copy.deepcopy(base)
                wrong[prop] = {"__wrong": True}
                add(name, f"wrong-type:{prop}", wrong)
                resolved = self.defs.get(ref_name(inner) or "", inner)
                if resolved.get("type") == "string" and "pattern" in resolved:
                    for bad in ("", "-leading", "has space", "trailing\n", "a" * 300):
                        v = copy.deepcopy(base)
                        v[prop] = bad
                        add(name, f"pattern:{prop}:{json.dumps(bad)[:20]}", v)
                    sample_text = base[prop] if isinstance(base[prop], str) else self.sample(resolved)
                    for ch in ("\n", "\r", "\u2028", "\u2029", "\U0001F600"):
                        v = copy.deepcopy(base)
                        v[prop] = sample_text[:-1] + ch + sample_text[-1:]
                        add(name, f"pattern-insert:{prop}:{json.dumps(ch)}", v)
                if resolved.get("format") == "date-time":
                    for bad in ("2026-01-01", "2026-01-01T00:00:00", "not-a-date", "2026-13-01T00:00:00Z",
                                "2026-01-01T00:00:00+0700", "2026-01-01 00:00:00Z", "2026-01-01T00:00:00+07",
                                "2026-01-01T00:00Z", "20260101T000000Z", "2026-02-29T00:00:00Z"):
                        v = copy.deepcopy(base)
                        v[prop] = bad
                        add(name, f"date-time:{prop}:{bad}", v)
                    v = copy.deepcopy(base)
                    v[prop] = "2026-05-06T07:08:09.123+07:00"
                    add(name, f"date-time-offset:{prop}", v)
                if "enum" in resolved:
                    v = copy.deepcopy(base)
                    v[prop] = "NOT_A_MEMBER"
                    add(name, f"enum:{prop}", v)
                if resolved.get("type") in ("integer", "number"):
                    for k, delta in (("minimum", -1), ("maximum", 1)):
                        if k in resolved:
                            v = copy.deepcopy(base)
                            v[prop] = resolved[k] + delta
                            add(name, f"{k}:{prop}", v)
                    if resolved.get("type") == "integer":
                        v = copy.deepcopy(base)
                        v[prop] = 1.5
                        add(name, f"fraction:{prop}", v)
                if "const" in resolved:
                    v = copy.deepcopy(base)
                    v[prop] = not resolved["const"] if isinstance(resolved["const"], bool) else resolved["const"] + 1
                    add(name, f"const:{prop}", v)
                if resolved.get("type") == "array" and "maxItems" in resolved:
                    v = copy.deepcopy(base)
                    v[prop] = [self.sample(resolved["items"])] * (resolved["maxItems"] + 1)
                    add(name, f"maxItems:{prop}", v)
                if resolved.get("type") == "string" and "maxLength" in resolved and "pattern" not in resolved:
                    v = copy.deepcopy(base)
                    v[prop] = "y" * (resolved["maxLength"] + 1)
                    add(name, f"maxLength:{prop}", v)
                    # Non-BMP characters: lengths count code points, not UTF-16 units.
                    v = copy.deepcopy(base)
                    v[prop] = "\U0001F600" * resolved["maxLength"]
                    add(name, f"maxLength-astral:{prop}", v)
                    v = copy.deepcopy(base)
                    v[prop] = "\U0001F600" * (resolved["maxLength"] + 1)
                    add(name, f"maxLength-astral-over:{prop}", v)
        return cases


def render_all() -> dict[Path, str]:
    schema = json.loads(SCHEMA_PATH.read_text(encoding="utf-8"))
    ipc = json.loads(IPC_PATH.read_text(encoding="utf-8"))
    problems = contract_checks.schema_errors(schema)
    if problems:
        raise SystemExit("schema subset errors: " + "; ".join(problems))
    model = Model(schema, ipc)
    rust = model.render_rust()
    ts = model.render_ts()
    cases = model.cases()
    bad_samples = [c for c in cases if c["label"] == "sample" and not c["valid"]]
    if bad_samples:
        raise SystemExit("generated samples invalid: " + ", ".join(c["def"] for c in bad_samples))
    cases_text = json.dumps({"_comment": HEADER, "cases": cases}, indent=1, ensure_ascii=True) + "\n"
    ts_cases = (f"// {HEADER}\n// Test-only: imported by contract self-tests, never by application code.\n\n"
                "export interface ContractCase {\n  def: string\n  label: string\n  value: unknown\n  valid: boolean\n}\n\n"
                "// Embedded as a JSON string so the type checker does not infer a literal union.\n"
                "export const CASES = JSON.parse(" + json.dumps(json.dumps(cases, ensure_ascii=True)) + ") as ContractCase[]\n")
    return {RUST_OUT: rust, TS_OUT: ts, CASES_OUT: cases_text, TS_CASES_OUT: ts_cases}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if generated files are stale")
    args = parser.parse_args()
    outputs = render_all()
    stale = []
    for path, text in outputs.items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current != text:
            stale.append(str(path.relative_to(ROOT)))
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text, encoding="utf-8")
    if args.check:
        print(json.dumps({"status": "STALE" if stale else "PASS_PARITY_GENERATED", "stale": stale}))
        return 1 if stale else 0
    print(json.dumps({"written": stale}))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
